#ifndef CHASSIS_TRACTION_CONFIG_H
#define CHASSIS_TRACTION_CONFIG_H

/* 0=关闭，1=只记录判定，2=空转降扭/抱死减制动，3=另允许有限空转制动。
 * 先用1采集和核对轮向、IMU轴向及误判，再单独构建2/3；不自动改变日常固件。 */
#ifndef CHASSIS_TRACTION_MODE
#define CHASSIS_TRACTION_MODE 0
#endif
#ifndef CHASSIS_TRACTION_CALIBRATED
#define CHASSIS_TRACTION_CALIBRATED 0
#endif
#if CHASSIS_TRACTION_MODE < 0 || CHASSIS_TRACTION_MODE > 3
#error CHASSIS_TRACTION_MODE must be 0, 1, 2 or 3.
#endif
#if CHASSIS_TRACTION_CALIBRATED != 0 && CHASSIS_TRACTION_CALIBRATED != 1
#error CHASSIS_TRACTION_CALIBRATED must be 0 or 1.
#endif
#if CHASSIS_TRACTION_MODE >= 2 && !CHASSIS_TRACTION_CALIBRATED
#error Verify traction axes and thresholds in shadow mode before setting CHASSIS_TRACTION_CALIBRATED=1.
#endif

/* 以下均为待实车验证初值。速度是轮缘沿滚动方向的 m/s，电流为DJI命令刻度。 */
#define CHASSIS_TRACTION_ABSOLUTE_SLIP_MPS 0.25f
#define CHASSIS_TRACTION_RELATIVE_SLIP 0.20f
#define CHASSIS_TRACTION_MIN_WHEEL_MPS 0.30f
#define CHASSIS_TRACTION_MIN_GROUND_MPS 0.40f
#define CHASSIS_TRACTION_RELEASE_RATIO 0.50f
#define CHASSIS_TRACTION_ENTER_MS 20U
#define CHASSIS_TRACTION_RELEASE_MS 40U
#define CHASSIS_TRACTION_RECOVERY_S 0.20f
/* 陈旧估计的额外误差容许量，不是车辆的加速度指令或经过标定的极限。 */
#define CHASSIS_TRACTION_ACCEL_ALLOWANCE_MPS2 8.0f
#define CHASSIS_TRACTION_YAW_ACCEL_ALLOWANCE_RADPS2 20.0f
#define CHASSIS_TRACTION_MAX_REFERENCE_AGE_MS 40U
#define CHASSIS_TRACTION_MAX_WHEEL_AGE_MS 20U
#define CHASSIS_TRACTION_BRAKE_GAIN 1000.0f
#define CHASSIS_TRACTION_MAX_BRAKE_CURRENT 300.0f
/* 固定底盘IMU绕Z角速度 -> 公共轮速wz符号，必须用双向原地旋转核对。 */
#ifndef CHASSIS_TRACTION_GYRO_Z_SIGN
#define CHASSIS_TRACTION_GYRO_Z_SIGN 1.0f
#endif

#endif
