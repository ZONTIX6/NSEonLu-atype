#ifndef CHASSIS_WHEEL_REDUNDANCY_CONFIG_H
#define CHASSIS_WHEEL_REDUNDANCY_CONFIG_H

/* 0=off, 1=shadow only, 2=replace the wheel estimate after validation. */
#ifndef CHASSIS_WHEEL_REDUNDANCY_MODE
#define CHASSIS_WHEEL_REDUNDANCY_MODE 0
#endif

#if CHASSIS_WHEEL_REDUNDANCY_MODE < 0 || CHASSIS_WHEEL_REDUNDANCY_MODE > 2
#error CHASSIS_WHEEL_REDUNDANCY_MODE must be 0, 1 or 2.
#endif

/* These are initial gating values, not measured slip limits. */
#define CHASSIS_WHEEL_REDUNDANCY_RESIDUAL_THRESHOLD_MPS 0.25f
#define CHASSIS_WHEEL_REDUNDANCY_DOMINANCE_RATIO 1.75f
#define CHASSIS_WHEEL_REDUNDANCY_MAX_REFERENCE_ERROR_MPS 0.30f
#define CHASSIS_WHEEL_REDUNDANCY_CONFIRM_SAMPLES 2U
#define CHASSIS_WHEEL_REDUNDANCY_REFERENCE_MAX_AGE_MS 40U

#endif
