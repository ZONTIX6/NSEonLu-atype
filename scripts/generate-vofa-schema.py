"""Generate the firmware channel indexes from the shared VOFA wire contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    schemas = json.loads((ROOT / "config/32_capture/vofa_schema.json").read_text(encoding="utf-8"))
    lines = ["/* Generated by scripts/generate-vofa-schema.py; edit vofa_schema.json. */",
             "#ifndef VOFA_SCHEMA_H", "#define VOFA_SCHEMA_H", ""]
    for number, schema in schemas.items():
        prefix = "VOFA_" + schema["name"].upper()
        names = [item["name"] for item in schema["channels"]]
        if len(names) > 109 or len(names) != len(set(names)):
            raise ValueError("Invalid channel contract")
        lines += [f"#define {prefix}_SCHEMA_ID {number}U", "enum {"]
        lines += [f"    {prefix}_{name.upper()} = {index}," for index, name in enumerate(names)]
        lines += [f"    {prefix}_CHANNELS = {len(names)}", "};", ""]
    return "\n".join(lines + ["#endif", ""])


def render_markdown():
    schemas = json.loads((ROOT / "config/32_capture/vofa_schema.json").read_text(encoding="utf-8"))
    lines = ["# VOFA 专用观测通道", "", "由 `scripts/generate-vofa-schema.py` 从工程的 JSON 通道定义生成。",
             "32 位字段以 `_hi` / `_lo` 拼接；未知年龄为 -1。有效位未置位的数据不可作为测量使用。", ""]
    for number, schema in schemas.items():
        lines += [f"## Schema {number}: {schema['name']}", "", "| 通道 | 字段 | 单位 |", "| --- | --- | --- |"]
        lines += [f"| I{i} | `{item['name']}` | {item['unit']} |" for i, item in enumerate(schema['channels'])]
        lines += ["", "有效位（I5）：", ""]
        lines += [f"- bit {bit}: `{name}`" for name, bit in schema['valid_bits'].items()]
        lines += [""]
        for name in ('state_encoding', 'provenance_encoding', 'wheel_masks_encoding'):
            if name in schema:
                lines += [f"`{name}`: {schema[name]}", ""]
        for flag_field in ('attempt_flags', 'yaw_control_flags'):
            if flag_field in schema:
                lines += [f"`{flag_field}`：", ""]
                lines += [f"- bit {bit}: `{name}`" for name, bit in schema[flag_field].items()]
                lines += [""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for relative, expected in (("application/runtime/vofa_schema.h", render()),
                               ("docs/vofa-observation-channels.md", render_markdown())):
        target = ROOT / relative
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                raise SystemExit("VOFA indexes/docs are stale; run scripts/generate-vofa-schema.py")
        else:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                target.write_text(expected, encoding="utf-8", newline="\n")
